/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require('node:assert/strict');
const { createHarness } = require('./messaging-test-helpers.cjs');

async function main() {
  const h = createHarness({ seedFixtures: false });
  const { signIntegrationAccess, verifyIntegrationAccess } = h.load('lib/integration/access.ts');
  const http = h.load('lib/integration/http.ts');
  const dashboard = h.load('lib/integration/dashboard.ts');
  const secret = 'integration-test-key-'.repeat(3);
  const saved = process.env.MESSAGING_SERVICE_SECRET;
  process.env.MESSAGING_SERVICE_SECRET = secret;
  const a = { kind: 'business', businessId: 'business-a' };
  const b = { kind: 'business', businessId: 'business-b' };
  const now = Date.now();
  const token = await signIntegrationAccess(secret, a, now);
  assert.equal(await verifyIntegrationAccess(secret, token, a, now), true);
  assert.equal(await verifyIntegrationAccess(secret, token, b, now), false);
  assert.equal(await verifyIntegrationAccess(secret, token, { kind: 'directory' }, now), false);
  assert.equal(await verifyIntegrationAccess(secret, token, a, now + 121000), false);
  assert.equal(await verifyIntegrationAccess('wrong-key-'.repeat(4), token, a, now), false);
  assert.equal(await verifyIntegrationAccess(secret, token + 'x', a, now), false);
  let called = 0;
  const request = (value) => new Request('http://localhost/api/integration/v1', { headers: value ? { authorization: `Bearer ${value}` } : {} });
  assert.equal((await http.integrationResponse(request(), a, async () => { called++; })).status, 401);
  assert.equal((await http.integrationResponse(request(token), b, async () => { called++; })).status, 401);
  assert.equal(called, 0);
  const success = await http.integrationResponse(request(token), a, async () => { called++; return { businessId: a.businessId }; });
  assert.equal(success.status, 200);
  assert.equal(success.headers.get('cache-control'), 'private, no-store');
  assert.equal((await success.json()).data.businessId, a.businessId);
  const profile = { name: 'Business A', vertical: 'eats', active: true, whatsappPhoneNumberId: '11111111', wabaId: '99999999', settings: { whatsapp: { accessToken: 'PRIVATE_TOKEN', verifyToken: 'PRIVATE_VERIFY' }, other: { keep: true } } };
  h.seed('businesses/business-a', profile);
  h.seed('businesses/business-b', { ...profile, name: 'Business B', whatsappPhoneNumberId: '22222222' });
  h.seed('conversations/a', { businessId: 'business-a', state: 'eats_start', context: { secret: 'PRIVATE_TOKEN' } });
  h.seed('conversations/b', { businessId: 'business-b', state: 'FOREIGN_STATE' });
  const conversations = await dashboard.integrationRead('business-a', 'conversations');
  assert.equal(conversations.conversations.length, 1);
  assert.equal(conversations.conversations[0].id, 'a');
  assert.ok(!JSON.stringify(conversations).includes('PRIVATE_TOKEN'));
  assert.ok(!JSON.stringify(await dashboard.integrationBusinesses()).includes('PRIVATE_TOKEN'));
  assert.equal((await dashboard.integrationRead('business-a', 'templates')).status, 'pending_setup');
  const setup = await dashboard.integrationSetup('business-a', { phoneNumberId: '33333333', wabaId: '44444444', connectedNumber: '+919876543210' });
  assert.equal(setup.phoneNumberId, '33333333');
  assert.equal(setup.wabaId, '44444444');
  assert.equal(h.read('businesses/business-b').whatsappPhoneNumberId, '22222222');
  assert.equal(h.read('businesses/business-a').settings.whatsapp.accessToken, 'PRIVATE_TOKEN');
  assert.equal(h.read('businesses/business-a').settings.other.keep, true);
  assert.ok(!JSON.stringify(setup).includes('PRIVATE_TOKEN'));
  await assert.rejects(dashboard.integrationSetup('business-a', { phoneNumberId: '22222222', wabaId: '', connectedNumber: '' }), /another business/);
  await assert.rejects(dashboard.integrationSetup('business-a', { phoneNumberId: '33333333', accessToken: 'forbidden' }));
  const writes = h.writes.length;
  const preview = await dashboard.integrationTest('business-a', { recipient: '919876543210', message: 'Hello' });
  assert.equal(preview.businessId, 'business-a');
  assert.equal(preview.sent, false);
  assert.equal(h.writes.length, writes);
  assert.equal(h.sends.length, 0);
  delete process.env.MESSAGING_SERVICE_SECRET;
  assert.equal((await http.integrationResponse(request(token), a, async () => null)).status, 503);
  if (saved !== undefined) process.env.MESSAGING_SERVICE_SECRET = saved;
  console.log('PASS: signed/expiring/business-scoped API access, fail-closed configuration, safe projections, tenant isolation, setup validation/uniqueness, no credential changes, local test without sends.');
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
